def replace_paragraph_text(paragraph, text):
    """Keep paragraph style and first-run formatting; replace only its wording."""
    if paragraph.runs:
        paragraph.runs[0].text = text
        for run in paragraph.runs[1:]:
            run.text = ""
    else:
        paragraph.add_run(text)


def replace_cell_text(cell, text):
    paragraph = cell.paragraphs[0]
    replace_paragraph_text(paragraph, text)
    for paragraph in cell.paragraphs[1:]:
        replace_paragraph_text(paragraph, "")


def set_paragraphs(document, replacements):
    for index, text in replacements.items():
        replace_paragraph_text(document.paragraphs[index], text)


